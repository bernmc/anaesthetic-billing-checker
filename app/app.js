function updateRvgDisplay() {
  const computed = RVG_BASE_RATE * (RVG_GAP_PCT / 100);
  if (rvgPrivateRateDisplay) {
    rvgPrivateRateDisplay.textContent = `$${computed.toFixed(2)}`;
  }
}

