// ── Rate defaults (editable via UI) ───────────────────────────────
let RVG_BASE_RATE = 106;           // 100% AMA RVG rate per unit
let RVG_GAP_PCT = 60;              // gap percentage applied
let PRIVATE_RATE_PER_UNIT = RVG_BASE_RATE * (RVG_GAP_PCT / 100); // derived
const NOGAP_MIN_PER_UNIT = 35;
const NOGAP_MAX_PER_UNIT = 45;

function recalcPrivateRate() {
  PRIVATE_RATE_PER_UNIT = RVG_BASE_RATE * (RVG_GAP_PCT / 100);
}

