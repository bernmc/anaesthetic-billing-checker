// ── Render: overall verdict traffic light ──────────────────────────
function renderVerdict(checks, warnings = []) {
  caseVerdictEl.classList.remove("hidden");

  const hasRed =
    checks.some((c) => c.status === "red") ||
    warnings.some((w) => w.severity === "hard_fail");
  const hasAmber =
    checks.some((c) => c.status === "amber") ||
    warnings.some((w) => w.severity === "soft_warning");

  let overall, label;
  if (hasRed)        { overall = "red";   label = "HARD FAIL — review red items below"; }
  else if (hasAmber) { overall = "amber"; label = "QUERY — review amber items below"; }
  else               { overall = "green"; label = "PASS — all checks green"; }

  const litR = overall === "red"   ? " lit" : "";
  const litA = overall === "amber" ? " lit" : "";
  const litG = overall === "green" ? " lit" : "";
  const vlCls = overall === "red" ? "vl-fail" : overall === "amber" ? "vl-query" : "vl-pass";

  caseVerdictEl.innerHTML = `
    <div class="verdict-bar">
      <div class="tl-housing">
        <div class="tl-light tl-red${litR}"></div>
        <div class="tl-light tl-amber${litA}"></div>
        <div class="tl-light tl-green${litG}"></div>
      </div>
      <span class="verdict-label ${vlCls}">${label}</span>
    </div>
  `;
}

// ── Render: safety checks ─────────────────────────────────────────
function renderSafetyChecks(checks) {
  safetyChecksEl.classList.remove("hidden");

  // Sort by severity: red (HARD FAIL) first, amber (QUERY), green (PASS)
  const rank = { red: 0, amber: 1, green: 2 };
  const sorted = [...checks].sort(
    (a, b) => (rank[a.status] ?? 9) - (rank[b.status] ?? 9)
  );

  const rows = sorted
    .map((ch) => {
      const dotCls =
        ch.status === "green" ? "dot-green" : ch.status === "amber" ? "dot-amber" : "dot-red";
      const labelCls =
        ch.label === "PASS" ? "label-pass" : ch.label === "QUERY" ? "label-query" : "label-fail";
      return `
        <div class="safety-item">
          <span class="traffic-dot ${dotCls}"></span>
          <div>
            <div class="safety-title">${ch.title} <span class="status-label ${labelCls}">${ch.label}</span></div>
            <div>${ch.message}</div>
          </div>
        </div>`;
    })
    .join("");

  safetyChecksEl.innerHTML = `
    <h2>Traffic-Light Safety Checks</h2>
    <div class="safety-list">${rows}</div>
  `;
}

// ── Render: warnings ──────────────────────────────────────────────
function renderWarnings(warnings) {
  warningsEl.classList.remove("hidden");

  if (warnings.length === 0) {
    warningsEl.innerHTML = `<h2>Audit Warnings</h2><p>No warnings.</p>`;
    return;
  }

  const html = warnings
    .map((w) => {
      const cls =
        w.severity === "hard_fail"
          ? "warning-hard"
          : w.severity === "soft_warning"
            ? "warning-soft"
            : "warning-context";
      const pill =
        w.severity === "hard_fail"
          ? "HARD FAIL"
          : w.severity === "soft_warning"
            ? "SOFT WARNING"
            : "CONTEXT CHECK";
      return `<div class="${cls}"><span class="warning-pill">${pill}</span> ${w.text}</div>`;
    })
    .join("");

  warningsEl.innerHTML = `<h2>Audit Warnings</h2>${html}`;
}

// ── Render: code breakdown table ──────────────────────────────────
function renderCodeBreakdown(uniqueCodes, counts) {
  codeBreakdownEl.classList.remove("hidden");

  const rows = uniqueCodes
    .map((code) => {
      const info = getCodeInfo(code);
      const desc = info ? info.description : "Unknown code (not in current data source)";
      const units = info && typeof info.units === "number" ? info.units : "n/a";
      const fee = info && typeof info.scheduleFee === "number" ? info.scheduleFee : null;
      const qty = counts[code] || 1;
      const totalUnits = typeof units === "number" ? units * qty : "n/a";
      const totalFee = fee !== null ? fee * qty : null;

      return `<tr>
        <td>${code}</td>
        <td>${qty}</td>
        <td>${desc}</td>
        <td>${typeof units === "number" ? units : "n/a"}</td>
        <td>${typeof totalUnits === "number" ? totalUnits : "n/a"}</td>
        <td>${fee !== null ? fmt(fee) : "n/a"}</td>
        <td>${totalFee !== null ? fmt(totalFee) : "n/a"}</td>
      </tr>`;
    })
    .join("");

  codeBreakdownEl.innerHTML = `
    <h2>Code Breakdown</h2>
    <div style="overflow-x:auto">
      <table class="table">
        <thead>
          <tr>
            <th>Code</th>
            <th>Qty</th>
            <th>Description</th>
            <th>Units/claim</th>
            <th>Total Units</th>
            <th>Sched Fee/claim</th>
            <th>Total Sched Fee</th>
          </tr>
        </thead>
        <tbody>
          ${rows || '<tr><td colspan="7">No valid 5-digit codes found.</td></tr>'}
        </tbody>
      </table>
    </div>
  `;
}

// ── Expected-for-case checks ──────────────────────────────────────
function buildExpectedChecks(uniqueCodes, procedures) {
  const items = [];

  // Valve case detection
  const isValve = procedures.some((p) => /valve/i.test(p));
  if (isValve) {
    items.push('<li class="check-ok">✅ Valve case detected</li>');
  } else {
    items.push('<li class="check-info">ℹ️ Valve case not detected</li>');
  }

  // Arterial line vs monitoring
  const has22012 = uniqueCodes.includes("22012");
  const has22025 = uniqueCodes.includes("22025");
  if (has22012 && has22025) {
    items.push('<li class="check-ok">✅ Arterial line code present (22025)</li>');
  } else if (has22012 && !has22025) {
    items.push('<li class="check-warn">⚠️ Arterial line code missing (22012 present, 22025 absent)</li>');
  } else {
    items.push('<li class="check-info">ℹ️ No arterial monitoring pattern detected (22012 absent)</li>');
  }

  return items.join("");
}

function getSpecialtyScope(uniqueCodes, procedures) {
  const hasCardiacProcedureFingerprint = procedures.some((p) => /cabg|cardiac|valve|re-exploration/i.test(p));
  const hasCardiacProxyCodes = ["20560", "22054", "22015", "22052"].some((code) => uniqueCodes.includes(code));
  const cardiacContext = hasCardiacProcedureFingerprint || hasCardiacProxyCodes;

  return {
    cardiacContext,
    message: cardiacContext
      ? "Cardiac-context rules active for this case (plus all general anaesthesia checks)."
      : "General anaesthesia checks active; cardiac-specific pattern checks are not applied.",
  };
}

// ── Helpers ───────────────────────────────────────────────────────
function countMatching(uniqueCodes, counts, predicate) {
  let total = 0;
  for (const code of uniqueCodes) {
    if (predicate(code)) total += counts[code] || 0;
  }
  return total;
}

function isProcedureCode(code) {
  const n = Number(code);
  return Number.isFinite(n) && n >= 20000 && n <= 21999;
}

function isTimeCode(code) {
  return /^23\d{3}$/.test(code);
}

function fmt(value) {
  return new Intl.NumberFormat("en-AU", { style: "currency", currency: "AUD" }).format(value);
}

// ── Catalog status ────────────────────────────────────────────────
async function refreshCatalogStatus() {
  if (!IS_HTTP || !catalogStatus) return;

  catalogStatus.className = "status-text status-warn";
  catalogStatus.textContent = "Checking catalog status…";

  try {
    const res = await fetch("/api/meta");
    const data = await res.json();
    if (!res.ok || !data.ok) throw new Error(data.error || "Status check failed");

    const meta = data.meta || {};
    const ts = meta.generatedAt ? new Date(meta.generatedAt).toLocaleString() : "unknown";
    catalogStatus.className = "status-text status-ok";
    catalogStatus.textContent = `Catalog: ${meta.totalItems || 0} items | Generated: ${ts} | Source: ${meta.source || "unknown"}`;
  } catch (err) {
    catalogStatus.className = "status-text status-error";
    catalogStatus.textContent = `Status check failed: ${err.message}`;
  }
}
