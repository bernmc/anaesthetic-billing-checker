import { XMLParser } from "fast-xml-parser";
import fs from "node:fs/promises";
import path from "node:path";

const BASE_URL = "https://www.mbsonline.gov.au";
const DOWNLOADS_INDEX = `${BASE_URL}/internet/mbsonline/publishing.nsf/Content/downloads`;

const ROOT_DIR = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const OUTPUT_FILE = path.join(ROOT_DIR, "app", "mbs-data.js");

// ── Main ──────────────────────────────────────────────────────────
async function main() {
  console.log("Fetching MBS downloads index…");
  const indexHtml = await fetchText(DOWNLOADS_INDEX);

  const latestPageUrl = findLatestDownloadsPage(indexHtml);
  if (!latestPageUrl) throw new Error("Could not locate latest downloads page on MBS Online.");
  console.log(`Latest downloads page: ${latestPageUrl}`);

  const pageHtml = await fetchText(latestPageUrl);
  const xmlUrl = findXmlDownloadUrl(pageHtml);
  if (!xmlUrl) throw new Error(`No XML download link found on ${latestPageUrl}`);
  console.log(`XML download: ${xmlUrl}`);

  console.log("Downloading XML (this may take a moment)…");
  const xmlText = await fetchText(xmlUrl);
  console.log(`XML size: ${(xmlText.length / 1024).toFixed(0)} KB`);

  const { items, notes } = parseXml(xmlText);
  const totalItems = Object.keys(items).length;
  console.log(`Parsed ${totalItems} MBS items.`);

  const meta = {
    source: "MBS Online official XML",
    downloadsIndexUrl: DOWNLOADS_INDEX,
    downloadsPageUrl: latestPageUrl,
    xmlDownloadUrl: xmlUrl,
    generatedAt: new Date().toISOString(),
    totalItems,
    parserNotes: notes,
  };

  const js =
    `// Auto-generated by update-mbs-data.mjs – do not edit\n` +
    `window.MBS_DATA = ${JSON.stringify(items, null, 2)};\n` +
    `window.MBS_DATA_META = ${JSON.stringify(meta, null, 2)};\n`;

  await fs.mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await fs.writeFile(OUTPUT_FILE, js, "utf8");

  console.log(`Wrote ${OUTPUT_FILE}`);
  console.log(`Total mapped items: ${totalItems}`);
}

// ── HTTP helpers ──────────────────────────────────────────────────
async function fetchText(url) {
  const res = await fetch(url, {
    headers: { "User-Agent": "AnaestheticBillingChecker/1.0" },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.text();
}

// ── Link extraction helpers ──────────────────────────────────────
function extractHrefs(html) {
  const out = [];
  const re = /href\s*=\s*"([^"]+)"/gi;
  let m;
  while ((m = re.exec(html))) out.push(m[1]);
  return out;
}

function toAbsolute(href) {
  if (/^https?:\/\//i.test(href)) return href;
  return href.startsWith("/") ? `${BASE_URL}${href}` : `${BASE_URL}/${href}`;
}

function dateScore(text) {
  const s = decodeURIComponent(text);
  const m8 = s.match(/(20\d{6})/);
  if (m8) return Number(m8[1]);
  const m6 = s.match(/\b(\d{6})\b/);
  if (m6) {
    const r = m6[1];
    return Number(`20${r.slice(0, 2)}${r.slice(2, 4)}${r.slice(4, 6)}`);
  }
  const mym = s.match(/(20\d{2})[-_](\d{2})/);
  if (mym) return Number(`${mym[1]}${mym[2]}01`);
  return 0;
}

function versionScore(text) {
  const m = decodeURIComponent(text).match(/version\s*(\d+)/i);
  return m ? Number(m[1]) : 1;
}

function findLatestDownloadsPage(html) {
  const candidates = extractHrefs(html)
    .map(toAbsolute)
    .filter((u) => /\/Content\/Downloads-/i.test(u));
  if (!candidates.length) return null;
  return candidates
    .map((url) => ({ url, score: dateScore(url) }))
    .sort((a, b) => b.score - a.score)[0].url;
}

function findXmlDownloadUrl(html) {
  const candidates = extractHrefs(html)
    .map(toAbsolute)
    .filter((u) => /\$FILE\/.*\.XML$/i.test(u));
  if (!candidates.length) return null;
  return candidates
    .map((url) => ({ url, d: dateScore(url), v: versionScore(url) }))
    .sort((a, b) => (b.d !== a.d ? b.d - a.d : b.v - a.v))[0].url;
}

// ── XML parsing ──────────────────────────────────────────────────
function parseXml(xmlText) {
  const parser = new XMLParser({
    ignoreAttributes: false,
    trimValues: true,
    parseTagValue: false,
    parseAttributeValue: false,
  });
  const root = parser.parse(xmlText);
  const items = {};
  const notes = [];

  walk(root, (node) => {
    if (!node || Array.isArray(node) || typeof node !== "object") return;

    const fields = scalarFields(node);
    const codes = codeCandidates(fields);
    if (!codes.length) return;

    const desc = bestDescription(fields);
    const fee = bestFee(fields);
    if (!desc) return;

    for (const code of codes) {
      const prev = items[code] || {};
      items[code] = {
        description: pickLonger(prev.description, desc),
        scheduleFee: prev.scheduleFee ?? fee,
      };
    }
  });

  // Normalise
  for (const [code, info] of Object.entries(items)) {
    if (info.scheduleFee === undefined) info.scheduleFee = null;
    if (!info.description) delete items[code];
  }

  notes.push("Descriptions and schedule fees extracted from latest official XML.");
  return { items, notes };
}

function walk(val, fn) {
  if (Array.isArray(val)) {
    for (const v of val) walk(v, fn);
    return;
  }
  if (!val || typeof val !== "object") return;
  fn(val);
  for (const child of Object.values(val)) walk(child, fn);
}

function scalarFields(node) {
  return Object.entries(node)
    .filter(([, v]) => typeof v === "string" || typeof v === "number")
    .map(([k, v]) => ({ key: k, value: String(v).trim() }));
}

function codeCandidates(fields) {
  const s = new Set();
  for (const f of fields) {
    if (/(item|code|num|number)/i.test(f.key) && /^\d{5}$/.test(f.value)) s.add(f.value);
  }
  return [...s];
}

function bestDescription(fields) {
  const c = fields
    .filter((f) => /(descr|description|itemtext|scheduletext|service|title|display)/i.test(f.key))
    .map((f) => f.value)
    .filter((v) => v.length >= 12 && !/^\d{5}$/.test(v));
  if (!c.length) return null;
  return c.sort((a, b) => b.length - a.length)[0];
}

function bestFee(fields) {
  const c = fields
    .filter((f) => /(schedule.?fee|fee|benefit|amt|amount|dollar)/i.test(f.key))
    .map((f) => parseMoney(f.value))
    .filter((v) => Number.isFinite(v) && v > 0 && v < 50000);
  if (!c.length) return null;
  return c.sort((a, b) => b - a)[0];
}

function parseMoney(s) {
  const c = String(s).replace(/[^0-9.-]/g, "");
  return c ? Number(c) : NaN;
}

function pickLonger(a, b) {
  if (!a) return b;
  if (!b) return a;
  return b.length > a.length ? b : a;
}

// ── Run ──────────────────────────────────────────────────────────
main().catch((err) => {
  console.error(err.message);
  process.exitCode = 1;
});
